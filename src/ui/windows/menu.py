"""
Example: the MENU window.

Template for the other windows (hud.py, pause.py...).
Texts and colours are NOT defined here: they live in PixelUI.
The window only asks PixelUI for an element by its key.
"""

import pygame as pg
import pygame_gui as ui

from src.ui.windows.base import Window


class MenuWindow(Window):
    name = "MENU"

    def build(self) -> None:
        screen_rect = pg.Rect((0, 0), self.pixel.manager.window_resolution)
        cx, cy = screen_rect.centerx, screen_rect.centery

        self.pixel.panel(
            "MENU_BKG",
            pg.Rect(cx - 320, cy - 450, 640, 900),
            color="#694420",  # background colour
            alpha=0,  # 0 = transparent, 255 = opaque
            container=self.panel,
        )

        # Title: text rendered as a surface with a black outline
        self.pixel.text_image(
            "TITLE",
            center=(cx, cy - 380),
            size=48,
            color=self.pixel.colors["title"],
            outline=self.pixel.colors["outline"],
            width=3,
            container=self.panel,
        )

        # Pixel-art button (image generated by make_button)
        self.play_btn = self.pixel.create_button(
            pg.Rect(cx - 100, cy + 350, 200, 100),
            (143, 46, 173),
            self.pixel.text("PLAY"),
            container=self.panel,
        )

        # Second pixel-art button, for QUIT
        self.quit_btn = self.pixel.create_button(
            pg.Rect(cx - 100, cy + 20, 200, 60),
            (100, 100, 100),
            "QUIT",
            container=self.panel,
        )

    def handle_event(self, event: pg.Event) -> str | None:
        if event.type == ui.UI_BUTTON_PRESSED:
            if event.ui_element is self.play_btn:
                return "GAME"
            if event.ui_element is self.quit_btn:
                return "QUIT"  # to be handled in main.py
        return None
